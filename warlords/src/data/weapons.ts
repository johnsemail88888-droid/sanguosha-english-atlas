/** Damage of one trigger pull, body shot, point blank (all pellets/projectile splash landing). */
export function weaponShotDamage(w: WeaponDef): number {
  const splash = w.projectile ? w.projectile.explodeDamage : 0;
  return (w.damage + splash) * w.pellets;
}

/** Sustained body-shot DPS inside falloffStart ignoring reloads and specials. */
export function weaponDps(w: WeaponDef): number {
  return weaponShotDamage(w) * w.fireRate;
}

/**
 * Seconds to deal `hp` damage with perfect body shots from the first trigger
 * pull (t = 0), including reloads when the magazine runs dry. Ignores
 * specials, armor and falloff. Returns Infinity if spawn ammo cannot do it.
 */
export function timeToKill(w: WeaponDef, hp: number): number {
  const perShot = weaponShotDamage(w);
  if (perShot <= 0 || w.fireRate <= 0) return Infinity;
  const shots = Math.ceil(hp / perShot);
  const totalAmmo = w.magSize * (1 + w.reserveMags);
  if (shots > totalAmmo) return Infinity;
  const reloads = w.magSize > 0 ? Math.floor((shots - 1) / w.magSize) : 0;
  return (shots - 1) / w.fireRate + reloads * w.reloadTime;
}
