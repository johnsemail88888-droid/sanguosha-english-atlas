// ── WeaponDef.specialParams semantics (implemented in sim combat hooks) ─────
// rapid          rampMul: fire-rate multiplier reached after `rampTime` s of continuous fire;
//                resetAfter: seconds without firing before the ramp resets.
// pierceArmor    ignoreArmor=1: hits ignore all armor (reduction AND 八卦/仁王/藤甲/白银 specials).
// genderBonus    mul: damage multiplier vs heroes of the opposite gender.
// freeze         slowPerStack: slow per stack; stackTime: stack lifetime (refreshed per hit);
//                freezeAt: stacks that trigger `freeze` for freezeTime s (stacks then reset);
//                immuneTime: seconds the target cannot be frozen again by this special.
// noArmorBonus   mul: damage multiplier vs targets with no armor equipped (troops/NPCs count).
// followUp       refund=1: a dodged/blocked shot returns its round to the magazine;
//                nextMul: multiplier of your next hit within `window` s.
// forceHit       dodgeIgnore=1: the projectile's explosion ignores dodge i-frames/八卦/dodgeChance.
// fireConvert    burnDps/burnTime: every hit applies (refreshes) `burn`.
// multiTarget    `pellets` rockets per trigger pull; each steers (turnRate rad/s) to a distinct
//                target within lockRadius m of the aim point (max maxTargets), else flies straight.
// dismount       dropMount=1: hit drops the target's mount as loot; slow/slowTime applied on hit.
// chainLightning chains: extra jumps; radius: jump range (m); mul: damage multiplier per jump.
// lifesteal      frac: fraction of damage dealt healed to the shooter.
//
// For projectile weapons `pellets` = projectiles per shot and `damage` = direct-hit damage;
// explodeDamage falls off to 50% at the edge of explodeRadius.
